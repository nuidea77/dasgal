/**
 * Regenerates src/components/exerciseAssets.ts from the files present in assets/exercises.
 * Metro needs static require() calls, so the map is generated rather than built at runtime.
 *   node scripts/gen-exercise-assets.js
 */
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'exercises');
const files = fs.existsSync(dir) ? fs.readdirSync(dir).sort() : [];
const photos = files.filter((f) => f.endsWith('.jpg')).map((f) => f.replace('.jpg', ''));
const gifs = files.filter((f) => f.endsWith('.gif')).map((f) => f.replace('.gif', ''));
const videos = files.filter((f) => f.endsWith('.mp4')).map((f) => f.replace('.mp4', ''));
const entry = (id, ext) => `  ${id}: require('../../assets/exercises/${id}.${ext}'),`;
const out = `// AUTO-GENERATED by scripts/gen-exercise-assets.js — do not edit by hand.

/** Still demonstration photos, keyed by exercise id. */
export const EXERCISE_PHOTOS: Record<string, number> = {
${photos.map((id) => entry(id, 'jpg')).join('\n')}
};

/** Animated demonstration GIFs, keyed by exercise id. */
export const EXERCISE_GIFS: Record<string, number> = {
${gifs.map((id) => entry(id, 'gif')).join('\n')}
};

/** Short silent looping demo clips (H.264), keyed by exercise id. */
export const EXERCISE_VIDEOS: Record<string, number> = {
${videos.map((id) => entry(id, 'mp4')).join('\n')}
};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'components', 'exerciseAssets.ts'), out);
console.log(`exerciseAssets.ts: ${photos.length} photos, ${gifs.length} gifs, ${videos.length} videos`);
